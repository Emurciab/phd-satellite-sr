# Define TrainingSample locally for loading (matches what was saved)
@dataclass
class TrainingSample:
    """Original TrainingSample format from generate_sta2_grid_parallel.py"""
    hr_sequence: np.ndarray = None
    lr_sequence: np.ndarray = None
    lr_20m_sequence: np.ndarray = None
    temporal_dates: Optional[List[str]] = None
    planet_dates: Optional[List[str]] = None
    tile_bounds: Optional[Dict] = None
    planet_bands: Optional[List[str]] = None
    s2_bands: Optional[List[str]] = None
    frame_quality: Optional[List] = None
    region_name: Optional[str] = None
    sequence_id: Optional[int] = None
    tile_id: Optional[str] = None
    s2_solar_zenith: Optional[List[float]] = None
    planet_solar_zenith: Optional[List[float]] = None


