#!/usr/bin/env python3
"""
Convert existing TrainingSample datasets to TrainingSample5Band format.

This script reads datasets generated by generate_sta2_grid_parallel.py (which have
proper temporal sequences from the same geographic location) and converts them to
the 5-band format needed for SuperDove training.

Key difference from convert_cache_to_5band.py:
- Works from properly structured TrainingSample objects (with temporal_dates, tile_bounds)
- Preserves the temporal sequence structure (same location, different times)
- Only needs to re-download tiles that need 5-band conversion

Band Mapping (SuperDove 8-band → 5-band):
=========================================
Planet bands: B2, B4, B6, B7, B8 (5 bands from 8-band sensor)
  - B2 (Blue)      → HR ch0 → S2 B2 (10m)
  - B4 (Green II)  → HR ch1 → S2 B3 (10m)
  - B6 (Red)       → HR ch2 → S2 B4 (10m)
  - B7 (Red Edge)  → HR ch3 → S2 B5 (20m)
  - B8 (NIR)       → HR ch4 → S2 B8A (20m)

Sentinel-2 bands: B2, B3, B4, B5, B8A
  - LR 10m: B2, B3, B4 (3 channels at ~77x77)
  - LR 20m: B5, B8A (2 channels at ~38x38)
"""

