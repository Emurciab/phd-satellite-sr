def downsample_hr_for_20m_flexible(hr_array: np.ndarray, factor: int = 2) -> np.ndarray:
    """
    Downsample HR array by factor for 20m band targets.
    Handles arbitrary shapes (not just power of 2).
    
    HR at 3m → target at 6m (factor 2) to match 20m/10m = 2x ratio
    Input: (H, W, C) at 3m → Output: (H//2, W//2, C) at 6m
    """
    from scipy.ndimage import zoom
    
    h, w, c = hr_array.shape
    new_h = h // factor
    new_w = w // factor
    
    # Trim to even dimensions if needed
    h_trim = new_h * factor
    w_trim = new_w * factor
    trimmed = hr_array[:h_trim, :w_trim, :]
    
    # Reshape and average
    result = trimmed.reshape(new_h, factor, new_w, factor, c).mean(axis=(1, 3))
    return result.astype(hr_array.dtype)


def convert_sample_to_5band(
    sample: TrainingSample,
    normalize: bool = True,
    scale_factor: float = 10000.0
) -> Optional[TrainingSample5Band]:
    """
    Convert a single TrainingSample to TrainingSample5Band format.
    
    Handles the conversion from 6-band SuperDove data to 5-band format:
    - Input: 6 bands ['B1', 'B2', 'B4', 'B6', 'B7', 'B8']
    - Output: 5 bands ['B2', 'B4', 'B6', 'B7', 'B8'] (drops B1)
    
    Band mapping for 5-band output:
    - HR ch0 (B2 Blue)     → 10m → S2 B2
    - HR ch1 (B4 Green II) → 10m → S2 B3  
    - HR ch2 (B6 Red)      → 10m → S2 B4
    - HR ch3 (B7 RedEdge)  → 20m → S2 B5
    - HR ch4 (B8 NIR)      → 20m → S2 B8A
    
    Args:
        sample: Original TrainingSample (from proper dataset with temporal sequences)
        normalize: Whether to normalize values to [0, 1]
        scale_factor: Normalization factor (default 10000 for reflectance)
    
    Returns:
        TrainingSample5Band or None if conversion fails
    """
    # Get tile bounds from sample
    if sample.tile_bounds is None:
        return None
        
    tile_bounds_coords = sample.tile_bounds.get('bounds', [])
    if not tile_bounds_coords:
        return None
    
    band_mode = sample.tile_bounds.get('band_mode', '4-band')
    planet_bands = sample.tile_bounds.get('planet_bands', [])
    sentinel_bands = sample.tile_bounds.get('sentinel_bands', [])
    
    # Check input data shape
    hr_shape = sample.hr_sequence.shape  # (T, H, W, C)
    n_frames = hr_shape[0]
    hr_bands = hr_shape[-1]
    
    # Handle different band configurations
    # 6-band SuperDove: ['B1', 'B2', 'B4', 'B6', 'B7', 'B8'] → drop B1 → 5 bands
    # 4-band Dove: ['B1', 'B2', 'B3', 'B4'] → keep all 4 bands
    
    hr_sequence_raw = sample.hr_sequence
    lr_sequence_raw = sample.lr_sequence
    
    if hr_bands == 6 and 'B8' in planet_bands:
        # SuperDove 6-band → 5-band (drop B1 at index 0)
        sensor_type = 'superdove'
        
        # Map from 6-band to 5-band: drop B1 (index 0)
        # Original: [B1, B2, B4, B6, B7, B8] indices [0, 1, 2, 3, 4, 5]
        # Output:   [B2, B4, B6, B7, B8] indices [1, 2, 3, 4, 5] from original
        hr_5band = hr_sequence_raw[:, :, :, 1:6]  # Drop B1, keep B2-B8 (5 bands)
        lr_5band = lr_sequence_raw[:, :, :, 1:6]  # Same for LR
        
        # 10m bands: B2, B4, B6 (indices 0, 1, 2 of 5-band output)
        hr_10m_sequence = hr_5band[:, :, :, 0:3]
        
        # 20m bands: B7, B8 (indices 3, 4 of 5-band output)
        hr_20m_full = hr_5band[:, :, :, 3:5]
        
        # Downsample 20m HR from 3m to 6m resolution
        hr_20m_frames = []
        for t in range(n_frames):
            hr_20m_frame = downsample_hr_for_20m_flexible(hr_20m_full[t], factor=2)
            hr_20m_frames.append(hr_20m_frame)
        hr_20m_sequence = np.stack(hr_20m_frames, axis=0)
        
        # LR bands
        lr_10m_sequence = lr_5band[:, :, :, 0:3]  # B2, B4, B6 → S2 B2, B3, B4
        lr_20m_sequence = lr_5band[:, :, :, 3:5]  # B7, B8 → S2 B5, B8A
        
        # Downsample LR 20m to half resolution
        lr_20m_frames = []
        for t in range(n_frames):
            lr_20m_frame = downsample_hr_for_20m_flexible(lr_20m_sequence[t], factor=2)
            lr_20m_frames.append(lr_20m_frame)
        lr_20m_sequence = np.stack(lr_20m_frames, axis=0)
        
        output_planet_bands = ['B2', 'B4', 'B6', 'B7', 'B8']
        output_s2_bands = ['B2', 'B3', 'B4', 'B5', 'B8A']
        hr_sequence = hr_5band
        
    elif hr_bands == 4:
        # Dove 4-band - keep as is
        sensor_type = 'dove'
        
        hr_sequence = hr_sequence_raw
        hr_10m_sequence = hr_sequence_raw[:, :, :, 0:3]  # RGB
        hr_20m_full = hr_sequence_raw[:, :, :, 3:4]  # NIR only
        
        # Downsample 20m HR
        hr_20m_frames = []
        for t in range(n_frames):
            hr_20m_frame = downsample_hr_for_20m_flexible(hr_20m_full[t], factor=2)
            hr_20m_frames.append(hr_20m_frame)
        hr_20m_sequence = np.stack(hr_20m_frames, axis=0)
        
        lr_10m_sequence = lr_sequence_raw[:, :, :, 0:3]
        lr_20m_sequence = lr_sequence_raw[:, :, :, 3:4] if lr_sequence_raw.shape[-1] > 3 else None
        
        if lr_20m_sequence is not None:
            lr_20m_frames = []
            for t in range(n_frames):
                lr_20m_frame = downsample_hr_for_20m_flexible(lr_20m_sequence[t], factor=2)
                lr_20m_frames.append(lr_20m_frame)
            lr_20m_sequence = np.stack(lr_20m_frames, axis=0)
        
        output_planet_bands = ['B1', 'B2', 'B3', 'B4']
        output_s2_bands = ['B2', 'B3', 'B4', 'B8A']
        
    else:
        # Unknown band configuration
        return None
    
    # Compute frame quality stats (on raw data before normalization)
    frame_quality_list = []
    for t in range(n_frames):
        fq = compute_combined_frame_quality(
            lr_10m_sequence[t], 
            hr_sequence[t],
            frame_idx=t
        )
        frame_quality_list.append(fq)
    
    # Normalize if requested (convert from reflectance 0-10000 to 0-1)
    if normalize:
        hr_sequence = np.clip(hr_sequence / scale_factor, 0, 1).astype(np.float32)
        hr_10m_sequence = np.clip(hr_10m_sequence / scale_factor, 0, 1).astype(np.float32)
        hr_20m_sequence = np.clip(hr_20m_sequence / scale_factor, 0, 1).astype(np.float32)
        lr_10m_sequence = np.clip(lr_10m_sequence / scale_factor, 0, 1).astype(np.float32)
        if lr_20m_sequence is not None:
            lr_20m_sequence = np.clip(lr_20m_sequence / scale_factor, 0, 1).astype(np.float32)
    
    # Create TrainingSample5Band
    return TrainingSample5Band(
        lr_sequence=lr_10m_sequence,
        hr_sequence=hr_sequence,
        lr_20m_sequence=lr_20m_sequence,
        hr_10m_sequence=hr_10m_sequence,
        hr_20m_sequence=hr_20m_sequence,
        temporal_dates=sample.temporal_dates,
        planet_dates=sample.planet_dates,
        region_name=sample.region_name,
        sequence_id=sample.sequence_id,
        tile_id=sample.tile_id,
        tile_bounds=sample.tile_bounds,
        sensor_type=sensor_type,
        planet_bands=output_planet_bands,
        sentinel_bands=output_s2_bands,
        s2_solar_zenith=sample.s2_solar_zenith,
        planet_solar_zenith=sample.planet_solar_zenith,
        frame_quality=frame_quality_list
    )


def convert_dataset(
    input_path: Path,
    output_dir: Path,
    max_samples: Optional[int] = None,
    filter_sensor: Optional[str] = None,
    normalize: bool = True,
    scale_factor: float = 10000.0
) -> List[TrainingSample5Band]:
    """
    Convert a full dataset from TrainingSample to TrainingSample5Band format.
    
    This converts datasets generated by generate_sta2_grid_parallel.py (which have
    proper temporal sequences - same location at different times) to the 5-band
    multi-resolution format needed for SR training.
    
    Args:
        input_path: Path to input dataset.pkl
        output_dir: Output directory for converted dataset
        max_samples: Maximum samples to convert
        filter_sensor: Filter by sensor type ('superdove', 'dove', or None)
        normalize: Whether to normalize to [0, 1]
        scale_factor: Normalization scale factor
    
    Returns:
        List of converted TrainingSample5Band objects
    """
    # Setup module mocking for unpickling
    setup_unpickle_modules()
    
    print(f"\n{'='*80}")
    print("CONVERTING DATASET TO 5-BAND FORMAT")
    print(f"{'='*80}")
    print(f"Input: {input_path}")
    print(f"Output: {output_dir}")
    print(f"Filter: {filter_sensor or 'all'}")
    print(f"Normalize: {normalize} (scale_factor={scale_factor})")
    print(f"{'='*80}\n")
    
    # Load input dataset
    with open(input_path, 'rb') as f:
        data = pickle.load(f)
    
    input_samples = data.get('samples', [])
    config = data.get('config', {})
    print(f"Loaded {len(input_samples)} samples from input dataset")
    if config:
        print(f"  Config: {config}")
    
    if max_samples:
        input_samples = input_samples[:max_samples]
        print(f"Limited to {max_samples} samples")
    
    # Convert samples
    converted_samples = []
    superdove_samples = []
    dove_samples = []
    errors = 0
    
    print("\nConverting samples...")
    start_time = time.time()
    
    for i, sample in enumerate(input_samples):
        try:
            converted = convert_sample_to_5band(
                sample=sample,
                normalize=normalize,
                scale_factor=scale_factor
            )
            
            if converted is not None:
                converted_samples.append(converted)
                if converted.sensor_type == 'superdove':
                    superdove_samples.append(converted)
                else:
                    dove_samples.append(converted)
            else:
                errors += 1
                
        except Exception as e:
            errors += 1
            if errors <= 5:
                print(f"  Error converting sample {i}: {e}")
        
        if (i + 1) % 100 == 0:
            elapsed = time.time() - start_time
            print(f"  Processed {i+1}/{len(input_samples)} "
                  f"(SuperDove: {len(superdove_samples)}, Dove: {len(dove_samples)}, "
                  f"Errors: {errors}) - {elapsed:.1f}s")
    
    print(f"\nConversion complete:")
    print(f"  SuperDove: {len(superdove_samples)}")
    print(f"  Dove: {len(dove_samples)}")
    print(f"  Errors: {errors}")
    
    # Apply filter
    if filter_sensor == 'superdove':
        converted_samples = superdove_samples
    elif filter_sensor == 'dove':
        converted_samples = dove_samples
    
    # Save output
    output_dir.mkdir(parents=True, exist_ok=True)
    
    if superdove_samples and (filter_sensor is None or filter_sensor == 'superdove'):
        superdove_output = output_dir / 'superdove_5band'
        superdove_output.mkdir(parents=True, exist_ok=True)
        
        dataset = {
            'samples': superdove_samples,
            'metadata': {
                'sensor_type': 'superdove',
                'n_samples': len(superdove_samples),
                'hr_bands': 5 if superdove_samples else 0,
                'hr_10m_bands': 3,
                'hr_20m_bands': 2,
                'lr_10m_bands': 3,
                'lr_20m_bands': 2,
                'planet_bands': ['B2', 'B4', 'B6', 'B7', 'B8'],
                's2_bands_10m': ['B2', 'B3', 'B4'],
                's2_bands_20m': ['B5', 'B8A'],
                'normalized': normalize,
                'scale_factor': scale_factor,
                'source_dataset': str(input_path),
            }
        }
        
        with open(superdove_output / 'dataset.pkl', 'wb') as f:
            pickle.dump(dataset, f)
        
        print(f"\nSaved {len(superdove_samples)} SuperDove samples to {superdove_output}")
        if superdove_samples:
            s = superdove_samples[0]
            print(f"  HR shape: {s.hr_sequence.shape}")
            print(f"  HR 10m shape: {s.hr_10m_sequence.shape}")
            print(f"  HR 20m shape: {s.hr_20m_sequence.shape}")
            print(f"  LR 10m shape: {s.lr_sequence.shape}")
            print(f"  temporal_dates: {s.temporal_dates}")
            print(f"  tile_bounds: {s.tile_bounds}")
    
    if dove_samples and (filter_sensor is None or filter_sensor == 'dove'):
        dove_output = output_dir / 'dove_4band'
        dove_output.mkdir(parents=True, exist_ok=True)
        
        dataset = {
            'samples': dove_samples,
            'metadata': {
                'sensor_type': 'dove',
                'n_samples': len(dove_samples),
                'hr_bands': 4,
                'hr_10m_bands': 3,
                'hr_20m_bands': 1,
                'lr_10m_bands': 3,
                'lr_20m_bands': 1,
                'planet_bands': ['B1', 'B2', 'B3', 'B4'],
                's2_bands_10m': ['B2', 'B3', 'B4'],
                's2_bands_20m': ['B8A'],
                'normalized': normalize,
                'scale_factor': scale_factor,
                'source_dataset': str(input_path),
            }
        }
        
        with open(dove_output / 'dataset.pkl', 'wb') as f:
            pickle.dump(dataset, f)
        
        print(f"\nSaved {len(dove_samples)} Dove samples to {dove_output}")
    
    return converted_samples


def main():
    parser = argparse.ArgumentParser(
        description='Convert TrainingSample dataset to TrainingSample5Band format',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
This script converts existing datasets that have proper temporal sequences
(same geographic location at different times) to the 5-band format.

Unlike convert_cache_to_5band.py which works from raw cache files,
this script preserves the temporal structure of the original dataset.

Example usage:
  python convert_dataset_to_5band.py --input ./data/datasets/STA2_2023/STA-2_dataset.pkl
  python convert_dataset_to_5band.py --input ./data/datasets/STA2_2023/STA-2_dataset.pkl --sensor superdove
        """
    )
    
    parser.add_argument('--input', type=str, required=True,
                        help='Path to input dataset.pkl file')
    parser.add_argument('--output-dir', type=str,
                        default='./data/sr_training/5band_converted',
                        help='Output directory for converted dataset')
    parser.add_argument('--max-samples', type=int, default=None,
                        help='Maximum samples to convert')
    parser.add_argument('--sensor', type=str, default=None,
                        choices=['superdove', 'dove'],
                        help='Filter by sensor type (default: both)')
    parser.add_argument('--no-normalize', action='store_true',
                        help='Keep raw reflectance values (0-10000)')
    
    args = parser.parse_args()
    
    input_path = Path(args.input)
    output_dir = Path(args.output_dir)
    
    if not input_path.exists():
        print(f"Error: Input file not found: {input_path}")
        sys.exit(1)
    
    samples = convert_dataset(
        input_path=input_path,
        output_dir=output_dir,
        max_samples=args.max_samples,
        filter_sensor=args.sensor,
        normalize=not args.no_normalize
    )
    
    print(f"\n{'='*80}")
    print("CONVERSION COMPLETE")
    print(f"{'='*80}")
    print(f"Total samples: {len(samples)}")
    print(f"Output directory: {output_dir}")
    print(f"{'='*80}")


if __name__ == '__main__':
    main()
