#!/usr/bin/env python3
"""
Convert STA-5/6 datasets to 5-band format.

This script reads datasets generated by generate_sta56_grid_parallel.py 
and converts 8-band SuperDove samples to the 5-band format needed for SR training.

Usage:
  1. First generate data: python generate_sta56_grid_parallel.py --year 2023
  2. Then convert to 5-band: python convert_dataset_to_5band_sta56.py --input ./data/datasets/sta56_2023

Band Mapping (SuperDove 8-band → 5-band):
=========================================
The 8-band SuperDove data is already stored with proper bands:
  - Planet bands: ['B2', 'B4', 'B6', 'B7', 'B8']
  - Sentinel bands: ['B2', 'B3', 'B4', 'B5', 'B8A']

5-band output structure:
  - HR: (T, 256, 256, 5) - Full 5 bands at 3m
  - HR 10m: (T, 256, 256, 3) - B2, B4, B6 (Blue, Green, Red)
  - HR 20m: (T, 128, 128, 2) - B7, B8 (RedEdge, NIR) downsampled to 6m
  - LR 10m: (T, 77, 77, 3) - S2 B2, B3, B4 at native 10m
  - LR 20m: (T, 38, 38, 2) - S2 B5, B8A at native 20m
"""

import sys
import os
sys.path.insert(0, os.path.join(os.path.dirname(__file__), '../..'))

import argparse
import pickle
from pathlib import Path
from typing import List, Dict, Optional
from dataclasses import dataclass, field
import numpy as np
import time


@dataclass
class TrainingSample:
    """Original TrainingSample format (for loading)"""
    lr_sequence: np.ndarray = None
    hr_sequence: np.ndarray = None
    temporal_dates: List[str] = None
    planet_dates: List[str] = None
    region_name: str = ''
    sequence_id: int = 0
    tile_id: int = 0
    tile_bounds: Dict = None
    s2_solar_zenith: Optional[List[float]] = None
    planet_solar_zenith: Optional[List[float]] = None
    lr_20m_sequence: Optional[np.ndarray] = None
    frame_quality: Optional[List[Dict]] = None


@dataclass
class TrainingSample5Band:
    """Training sample with full 5-band HR data for SuperDove images.
    
    Expected shapes:
        lr_sequence:     (T, 77, 77, 3)   - S2 B2, B3, B4 at 10m
        lr_20m_sequence: (T, 38, 38, 2)   - S2 B5, B8A at 20m  
        hr_sequence:     (T, 256, 256, 5) - All 5 Planet bands at 3m
        hr_10m_sequence: (T, 256, 256, 3) - Planet B2, B4, B6 at 3m
        hr_20m_sequence: (T, 128, 128, 2) - Planet B7, B8 at 6m (downsampled)
    """
    # Core sequences
    lr_sequence: np.ndarray  # (T, 77, 77, 3) - 10m bands at native resolution
    hr_sequence: np.ndarray  # (T, 256, 256, 5) - Full HR (5 for SuperDove)
    lr_20m_sequence: Optional[np.ndarray] = None  # (T, 38, 38, 2) - 20m bands at native
    
    # Split HR for multi-resolution training
    hr_10m_sequence: Optional[np.ndarray] = None  # (T, 256, 256, 3) - RGB bands only
    hr_20m_sequence: Optional[np.ndarray] = None  # (T, 128, 128, 2) - RedEdge/NIR at 6m
    
    # Metadata
    temporal_dates: List[str] = field(default_factory=list)
    planet_dates: List[str] = field(default_factory=list)
    region_name: str = ''
    sequence_id: int = 0
    tile_id: int = 0
    tile_bounds: Dict = field(default_factory=dict)
    
    # Band configuration
    sensor_type: str = 'superdove'
    planet_bands: List[str] = field(default_factory=lambda: ['B2', 'B4', 'B6', 'B7', 'B8'])
    sentinel_bands: List[str] = field(default_factory=lambda: ['B2', 'B3', 'B4', 'B5', 'B8A'])
    
    # Solar zenith angles
    s2_solar_zenith: Optional[List[float]] = None
    planet_solar_zenith: Optional[List[float]] = None
    
    # Quality metrics
    frame_quality: Optional[List[Dict]] = None


def setup_unpickle_modules():
    """Setup mock modules for unpickling TrainingSample objects."""
    class MockModule:
        TrainingSample = TrainingSample
    
    # Try to load the actual module first
    sys.modules['generate_sta56_grid_parallel'] = MockModule()
    sys.modules['generate_sta2_grid_parallel'] = MockModule()


def downsample_hr_for_20m(hr_array: np.ndarray, factor: int = 2) -> np.ndarray:
    """
    Downsample HR array by factor for 20m band targets.
    HR at 3m → target at 6m (factor 2) to match 20m/10m = 2x ratio
    """
    h, w, c = hr_array.shape
    new_h = h // factor
    new_w = w // factor
    
    h_trim = new_h * factor
    w_trim = new_w * factor
    trimmed = hr_array[:h_trim, :w_trim, :]
    
    result = trimmed.reshape(new_h, factor, new_w, factor, c).mean(axis=(1, 3))
    return result.astype(hr_array.dtype)


def compute_frame_quality(lr_frame: np.ndarray, hr_frame: np.ndarray, frame_idx: int = 0) -> Dict:
    """Compute combined quality stats for both LR and HR frames."""
    def get_stats(arr):
        total = arr.size
        nan_frac = np.sum(np.isnan(arr)) / total
        zero_frac = np.sum(np.abs(arr) < 0.01) / total  # Near-zero
        valid_frac = 1.0 - nan_frac - zero_frac
        return {'nan_frac': nan_frac, 'zero_frac': zero_frac, 'valid_frac': valid_frac}
    
    lr_stats = get_stats(lr_frame)
    hr_stats = get_stats(hr_frame)
    
    return {
        'frame_idx': frame_idx,
        'lr_valid_frac': lr_stats['valid_frac'],
        'hr_valid_frac': hr_stats['valid_frac'],
        'is_good': lr_stats['valid_frac'] > 0.85 and hr_stats['valid_frac'] > 0.85
    }


def convert_sample_to_5band(sample: TrainingSample, normalize: bool = True,
                            scale_factor: float = 10000.0,
                            input_already_normalized: bool = False) -> Optional[TrainingSample5Band]:
    """
    Convert a single TrainingSample to TrainingSample5Band format.
    
    Only processes 8-band SuperDove samples (band_mode == '8-band').
    Skips 4-band Dove samples.
    
    Args:
        sample: Input TrainingSample
        normalize: Whether to normalize output to [0,1]
        scale_factor: Scale factor for normalization (ignored if input already normalized)
        input_already_normalized: If True, skip normalization (data is already in [0,1])
    """
    if sample.tile_bounds is None:
        return None
    
    band_mode = sample.tile_bounds.get('band_mode', '4-band')
    planet_bands = sample.tile_bounds.get('planet_bands', [])
    sentinel_bands = sample.tile_bounds.get('sentinel_bands', [])
    
    # Only process 8-band SuperDove
    if band_mode != '8-band':
        return None
    
    # Verify bands match expected 5-band configuration
    expected_planet = ['B2', 'B4', 'B6', 'B7', 'B8']
    expected_sentinel = ['B2', 'B3', 'B4', 'B5', 'B8A']
    
    if planet_bands != expected_planet:
        print(f"    ⚠️ Unexpected Planet bands: {planet_bands}")
        return None
    
    hr_sequence = sample.hr_sequence  # (T, 256, 256, 5)
    lr_sequence = sample.lr_sequence  # (T, 77, 77, 3) - 10m bands
    lr_20m_sequence = sample.lr_20m_sequence  # (T, 38, 38, 2) - 20m bands
    
    if hr_sequence is None or hr_sequence.shape[-1] != 5:
        return None
    
    n_frames = hr_sequence.shape[0]
    
    # Split HR into 10m and 20m components
    hr_10m_sequence = hr_sequence[:, :, :, :3]  # B2, B4, B6 → S2 B2, B3, B4
    hr_20m_full = hr_sequence[:, :, :, 3:]  # B7, B8 → S2 B5, B8A
    
    # Downsample 20m HR from 256 to 128 (3m → 6m)
    hr_20m_frames = []
    for t in range(n_frames):
        hr_20m_frame = downsample_hr_for_20m(hr_20m_full[t], factor=2)
        hr_20m_frames.append(hr_20m_frame)
    hr_20m_sequence = np.stack(hr_20m_frames, axis=0)
    
    # Compute frame quality (on raw data before normalization)
    frame_quality_list = []
    for t in range(n_frames):
        fq = compute_frame_quality(lr_sequence[t], hr_sequence[t], t)
        frame_quality_list.append(fq)
    
    # Normalize if requested AND input is not already normalized
    if normalize and not input_already_normalized:
        hr_sequence = np.clip(hr_sequence / scale_factor, 0, 1).astype(np.float32)
        hr_10m_sequence = np.clip(hr_10m_sequence / scale_factor, 0, 1).astype(np.float32)
        hr_20m_sequence = np.clip(hr_20m_sequence / scale_factor, 0, 1).astype(np.float32)
        lr_sequence = np.clip(lr_sequence / scale_factor, 0, 1).astype(np.float32)
        if lr_20m_sequence is not None:
            lr_20m_sequence = np.clip(lr_20m_sequence / scale_factor, 0, 1).astype(np.float32)
    else:
        # Ensure float32 dtype
        hr_sequence = hr_sequence.astype(np.float32)
        hr_10m_sequence = hr_10m_sequence.astype(np.float32)
        hr_20m_sequence = hr_20m_sequence.astype(np.float32)
        lr_sequence = lr_sequence.astype(np.float32)
        if lr_20m_sequence is not None:
            lr_20m_sequence = lr_20m_sequence.astype(np.float32)
    
    return TrainingSample5Band(
        lr_sequence=lr_sequence,
        hr_sequence=hr_sequence,
        lr_20m_sequence=lr_20m_sequence,
        hr_10m_sequence=hr_10m_sequence,
        hr_20m_sequence=hr_20m_sequence,
        temporal_dates=sample.temporal_dates or [],
        planet_dates=sample.planet_dates or [],
        region_name=sample.region_name or 'STA-5/6',
        sequence_id=sample.sequence_id or 0,
        tile_id=sample.tile_id or 0,
        tile_bounds=sample.tile_bounds or {},
        sensor_type='superdove',
        planet_bands=expected_planet,
        sentinel_bands=expected_sentinel,
        s2_solar_zenith=sample.s2_solar_zenith,
        planet_solar_zenith=sample.planet_solar_zenith,
        frame_quality=frame_quality_list
    )


def main():
    parser = argparse.ArgumentParser(
        description='Convert STA-5/6 dataset to 5-band format',
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  # Convert 2023 dataset
  python convert_dataset_to_5band_sta56.py --input ./data/datasets/sta56_2023

  # Convert 2024 dataset  
  python convert_dataset_to_5band_sta56.py --input ./data/datasets/sta56_2024

  # Convert with custom output path
  python convert_dataset_to_5band_sta56.py --input ./data/datasets/sta56_2023 --output ./data/sr_training/sta56_2023_5band
        """
    )
    parser.add_argument('--input', type=str, required=True,
                       help='Input directory containing dataset.pkl')
    parser.add_argument('--output', type=str, default=None,
                       help='Output directory for 5-band dataset (default: input_dir_5band)')
    parser.add_argument('--max-samples', type=int, default=None,
                       help='Maximum samples to convert')
    parser.add_argument('--no-normalize', dest='normalize', action='store_false',
                       help='Keep raw reflectance values (default: normalize to [0,1])')
    parser.set_defaults(normalize=True)
    
    args = parser.parse_args()
    
    # Setup paths
    input_dir = Path(args.input)
    input_path = input_dir / 'dataset.pkl'
    
    if not input_path.exists():
        print(f"❌ Input dataset not found: {input_path}")
        return
    
    if args.output:
        output_dir = Path(args.output)
    else:
        output_dir = input_dir.parent / f"{input_dir.name}_5band"
    
    output_dir.mkdir(parents=True, exist_ok=True)
    
    print("=" * 80)
    print("🔄 CONVERTING STA-5/6 DATASET TO 5-BAND FORMAT")
    print("=" * 80)
    print(f"\nInput:  {input_path}")
    print(f"Output: {output_dir}")
    print(f"Normalize: {args.normalize}")
    print("=" * 80)
    
    # Setup unpickling
    setup_unpickle_modules()
    
    # Load input dataset
    print(f"\n📂 Loading input dataset...")
    start_time = time.time()
    
    with open(input_path, 'rb') as f:
        data = pickle.load(f)
    
    # Handle both list format (old) and dict format (new)
    if isinstance(data, list):
        input_samples = data
        config = {}
    else:
        input_samples = data.get('samples', data) if isinstance(data, dict) else data
        config = data.get('config', {}) if isinstance(data, dict) else {}
    
    # If still not a list, it might be the samples directly
    if not isinstance(input_samples, list):
        input_samples = [input_samples] if input_samples is not None else []
    
    print(f"   Loaded {len(input_samples)} samples")
    if config:
        print(f"   Config: {config}")
    
    # Check if input is already normalized
    input_already_normalized = config.get('normalized', False)
    if input_already_normalized:
        print(f"   ℹ️  Input data is already normalized to [0, 1]")
    
    if args.max_samples:
        input_samples = input_samples[:args.max_samples]
        print(f"   Limited to {args.max_samples} samples")
    
    # Convert samples
    print(f"\n🔄 Converting samples to 5-band format...")
    
    converted_samples = []
    skipped_4band = 0
    errors = 0
    
    for i, sample in enumerate(input_samples):
        try:
            converted = convert_sample_to_5band(
                sample=sample,
                normalize=args.normalize,
                input_already_normalized=input_already_normalized
            )
            
            if converted is not None:
                converted_samples.append(converted)
            else:
                # Check why it was skipped
                if hasattr(sample, 'tile_bounds') and sample.tile_bounds and sample.tile_bounds.get('band_mode') != '8-band':
                    skipped_4band += 1
                else:
                    errors += 1
                    
        except Exception as e:
            errors += 1
            if errors <= 5:
                print(f"   ❌ Error converting sample {i}: {e}")
        
        if (i + 1) % 100 == 0 or (i + 1) == len(input_samples):
            print(f"   Progress: {i+1}/{len(input_samples)} "
                  f"(converted: {len(converted_samples)}, skipped 4-band: {skipped_4band}, errors: {errors})")
    
    print(f"\n📊 Conversion Summary:")
    print(f"   Input samples:     {len(input_samples)}")
    print(f"   5-band converted:  {len(converted_samples)}")
    print(f"   4-band skipped:    {skipped_4band}")
    print(f"   Errors:            {errors}")
    
    if len(converted_samples) == 0:
        print("\n❌ No samples were converted! (All samples may be 4-band Dove)")
        return
    
    # Save output
    print(f"\n💾 Saving 5-band dataset...")
    
    output_path = output_dir / 'dataset_5band.pkl'
    
    # Verify shapes
    sample = converted_samples[0]
    print(f"\n   Sample shapes:")
    print(f"     lr_sequence:     {sample.lr_sequence.shape}")
    print(f"     hr_sequence:     {sample.hr_sequence.shape}")
    if sample.lr_20m_sequence is not None:
        print(f"     lr_20m_sequence: {sample.lr_20m_sequence.shape}")
    print(f"     hr_10m_sequence: {sample.hr_10m_sequence.shape}")
    print(f"     hr_20m_sequence: {sample.hr_20m_sequence.shape}")
    
    # Value ranges
    print(f"\n   Value ranges (after {'normalization' if args.normalize else 'no normalization'}):")
    print(f"     lr_sequence:  [{sample.lr_sequence.min():.4f}, {sample.lr_sequence.max():.4f}]")
    print(f"     hr_sequence:  [{sample.hr_sequence.min():.4f}, {sample.hr_sequence.max():.4f}]")
    
    dataset = {
        'samples': converted_samples,
        'metadata': {
            'region': 'STA-5/6',
            'sensor_type': 'superdove',
            'n_samples': len(converted_samples),
            'sequence_length': sample.hr_sequence.shape[0],
            'hr_bands': 5,
            'hr_10m_bands': 3,
            'hr_20m_bands': 2,
            'lr_10m_bands': 3,
            'lr_20m_bands': 2,
            'planet_bands': ['B2', 'B4', 'B6', 'B7', 'B8'],
            's2_bands_10m': ['B2', 'B3', 'B4'],
            's2_bands_20m': ['B5', 'B8A'],
            'normalized': args.normalize,
            'scale_factor': 10000.0 if args.normalize else None,
            'hr_tile_size': 256,
            'lr_10m_tile_size': 77,
            'lr_20m_tile_size': 38,
            'hr_20m_tile_size': 128,
            'source_dataset': str(input_path)
        }
    }
    
    with open(output_path, 'wb') as f:
        pickle.dump(dataset, f, protocol=4)
    
    elapsed = time.time() - start_time
    
    print("\n" + "=" * 80)
    print("✅ CONVERSION COMPLETE!")
    print("=" * 80)
    print(f"Output saved: {output_path}")
    print(f"Samples: {len(converted_samples)} 5-band SuperDove samples")
    print(f"Time: {elapsed:.1f}s")
    print("=" * 80)


if __name__ == '__main__':
    main()
